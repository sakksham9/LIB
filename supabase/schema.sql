-- Reference schema for PageTurn Library System with Role-Based Authentication
-- Hibernate automatically creates / updates tables on startup (spring.jpa.hibernate.ddl-auto=update).

-- 1. Books Table
create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text,
  isbn text,
  publication_year integer,
  description text,
  cover_url text,
  rating integer,
  available_copies integer default 1
);
create index if not exists idx_books_title on public.books(title);
create index if not exists idx_books_isbn on public.books(isbn);
create index if not exists idx_books_category on public.books(category);

-- 2. Users Table (Admin and Student Accounts)
create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text not null,
  full_name text not null,
  email text unique,
  phone text,
  student_id_number text,
  department text,
  role text not null, -- 'ADMIN' or 'STUDENT'
  status text not null default 'ACTIVE', -- 'ACTIVE' or 'DEACTIVATED'
  created_at timestamp without time zone not null default now(),
  updated_at timestamp without time zone
);
create index if not exists idx_user_username on public.app_users(username);
create index if not exists idx_user_email on public.app_users(email);
create index if not exists idx_user_student_id on public.app_users(student_id_number);
create index if not exists idx_user_role on public.app_users(role);
create index if not exists idx_user_status on public.app_users(status);

-- 3. Authentication Tokens
create table if not exists public.auth_tokens (
  id bigint generated by default as identity primary key,
  token text not null unique,
  user_id bigint not null references public.app_users(id) on delete cascade,
  created_at timestamp without time zone not null default now(),
  expires_at timestamp without time zone not null
);
create index if not exists idx_token_value on public.auth_tokens(token);
create index if not exists idx_token_expires on public.auth_tokens(expires_at);

-- 4. Borrow Transactions (Linked to student account)
create table if not exists public.borrow_records (
  id bigint generated by default as identity primary key,
  book_id bigint not null,
  book_title text not null,
  student_id bigint,
  borrower_name text not null,
  borrower_contact text,
  borrowed_at timestamp without time zone not null default now(),
  due_date date,
  returned_at timestamp without time zone,
  status text not null default 'BORROWED',
  fine_amount double precision default 0.0,
  days_overdue integer default 0,
  fine_paid boolean default false,
  last_reminded_at timestamp without time zone,
  reminder_count integer default 0
);
create index if not exists idx_borrow_book_id on public.borrow_records(book_id);
create index if not exists idx_borrow_status on public.borrow_records(status);
create index if not exists idx_borrow_borrower on public.borrow_records(borrower_name);
create index if not exists idx_borrow_student_id on public.borrow_records(student_id);

-- 5. Book Reservations (Student Book Reservations)
create table if not exists public.book_reservations (
  id bigint generated by default as identity primary key,
  book_id bigint not null,
  book_title text not null,
  student_id bigint not null references public.app_users(id) on delete cascade,
  student_name text not null,
  student_contact text,
  reserved_at timestamp without time zone not null default now(),
  expiry_date date,
  status text not null default 'PENDING', -- 'PENDING', 'READY_FOR_PICKUP', 'FULFILLED', 'CANCELLED'
  notes text
);
create index if not exists idx_res_student on public.book_reservations(student_id);
create index if not exists idx_res_book on public.book_reservations(book_id);
create index if not exists idx_res_status on public.book_reservations(status);
